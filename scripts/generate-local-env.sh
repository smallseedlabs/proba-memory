#!/usr/bin/env bash
# Writes a local .env with random passwords for docker-compose.yml (nothing in this repository has a default password).
#   scripts/generate-local-env.sh            -> creates .env (refuses to overwrite)
#   scripts/generate-local-env.sh --force    -> replaces .env (the old passwords stop working: `docker compose down -v` first)
# The values are hex (URL-safe: both passwords are placed inside URLs). Never commit the result; .env is gitignored.
set -euo pipefail

cd "$(dirname "$0")/.."
if [ -e .env ] && [ "${1:-}" != "--force" ]; then
  echo ".env already exists; pass --force to replace it" >&2
  exit 1
fi

secret() { openssl rand -hex "${1:-24}"; }

REDIS_PASSWORD="$(secret)"
POSTGRES_PASSWORD="$(secret)"

umask 077
cat > .env <<ENV
# Generated by scripts/generate-local-env.sh. Local only; never commit.
# Read by docker compose (passwords) and by the host-side npm scripts and tests (URLs, users).
POSTGRES_USER=proba
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
REDIS_USER=proba
REDIS_PASSWORD=${REDIS_PASSWORD}
DATABASE_URL=postgresql://proba:${POSTGRES_PASSWORD}@127.0.0.1:25432/proba_memory
REDIS_URL=redis://proba:${REDIS_PASSWORD}@127.0.0.1:26379
ENV
echo "wrote .env with random passwords (Postgres and Redis user: proba)"
echo "next: npm run docker:up && npm run migrate"
